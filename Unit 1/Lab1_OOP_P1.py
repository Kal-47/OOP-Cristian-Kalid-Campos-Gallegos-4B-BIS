class Keyboard:
  def __init__(self, size, brand, layout):
    #self: se utiliza para decirle  a python que objeto pertenecen los atributos
    self.size = size
    self.brand = brand
    self.layout = layout

  def type(self):
    print("The keyboard is typing")

  def mayus(self):
    print("The keyboard is in BloqMayus Mode")

  def desc(self):
    print(f"Size: {self.size} "
          f"Brand: {self.brand} "
          f"Layout: {self.layout}")

## Create an instance using the class "table"
keyboard_1 = Keyboard("100%","Logitech","Spanish (Latin America)")
keyboard_2 = Keyboard("60%","Ryzen","US")

# We access to the object(Instance) "Table 1" to call its data
print(keyboard_1.size)
print(keyboard_2.brand)
keyboard_1.type()
keyboard_2.desc()


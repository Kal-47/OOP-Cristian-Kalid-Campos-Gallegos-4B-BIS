# @title
class BankAccount:
  def __init__(self, holders_name, __balance):
    self.holders_name = holders_name
    self.balance = __balance

  def deposit(self):
    money_r = int(input("Insert the money to deposit:"))
    if money_r > 0:
      self.balance += money_r
      print(f"Actual balance: {self.balance}")
    else: print("ERROR: the value to deposit is to small")

  def withdraw(self):
    money_w = int(input("Insert the money to withdraw: "))
    if money_w < self.balance:
      self.balance -= money_w
      print(f"Actual balance: {self.balance}")
    else:
      print("ERROR: You dont have enough money to withdraw, try with less money")